#!/usr/bin/env node
/**
 * Issue #483 — derive MCP tool/resource/prompt counts from mcp-catalog.ts into
 * every shipped surface (web bundle, docs, READMEs).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadMcpCatalog } from './lib/parse-mcp-catalog.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { counts } = loadMcpCatalog(root);
const { tools, resources, prompts } = counts;

function read(rel) {
  return readFileSync(join(root, rel), 'utf8');
}

function write(rel, content) {
  writeFileSync(join(root, rel), content, 'utf8');
}

function replace(rel, pairs) {
  let content = read(rel);
  for (const [from, to] of pairs) {
    if (!content.includes(from)) {
      throw new Error(`generate-mcp-catalog-surfaces: ${rel} missing expected fragment: ${from}`);
    }
    content = content.replace(from, to);
  }
  write(rel, content);
}

write(
  'apps/web/src/lib/mcp-catalog.generated.ts',
  `/** Generated by scripts/generate-mcp-catalog-surfaces.mjs — do not edit. */\n` +
    `export const MCP_CATALOG_COUNTS = {\n` +
    `  tools: ${tools},\n` +
    `  resources: ${resources},\n` +
    `  prompts: ${prompts},\n` +
    `} as const;\n`,
);

replace('README.md', [
  ['an MCP server (130+ tools)', `an MCP server (${tools} tools)`],
  ['server with **137 tools**', `server with **${tools} tools**`],
  ['MCP server (137 tools)', `MCP server (${tools} tools)`],
]);

replace('apps/server/README.md', [
  [
    '**Tool catalog** (207 — `modules/mcp/mcp-tools.ts`; see `test/mcp.e2e-spec.ts`\'s\n`ALL_TOOLS`',
    `**Tool catalog** (${tools} — \`modules/mcp/mcp-catalog.ts\`; see \`test/mcp.e2e-spec.ts\`'s\n\`MCP_TOOL_NAMES\``,
  ],
]);

replace('website/docs/index.md', [['**137-tool**', `**${tools}-tool**`]]);

replace('website/docs/ai/capabilities.md', [['server** (137 tools)', `server** (${tools} tools)`]]);

replace('website/docs/ai/reference.md', [
  [
    '- **Tools:** 130+ covering campaigns, quests, objectives, story arcs/beats/branches,\n' +
      '  NPCs, locations, factions, characters, encounters and combatants, dice, sessions,\n' +
      '  notes, the inbox, proposals, the AI Dungeon Master seat, members, rule packs, the\n' +
      '  session-zero charter, audit, and export.\n' +
      '  Call `tools/list` for the live catalogue with full input schemas — every tool\'s\n' +
      '  arguments are strictly validated and described.\n' +
      '- **Resources & prompts:** read surfaces (campaigns, campaign summary, party, session\n' +
      '  recaps, the session-zero charter) are also exposed as MCP **resources**, and the\n' +
      '  server ships prep/recap **prompts** — call `resources/list` and `prompts/list` to\n' +
      '  discover them.',
    `- **Tools:** ${tools} covering campaigns, quests, objectives, story arcs/beats/branches,\n` +
      '  NPCs, locations, factions, characters, encounters and combatants, dice, sessions,\n' +
      '  notes, the inbox, proposals, the AI Dungeon Master seat, members, rule packs, the\n' +
      '  session-zero charter, audit, and export.\n' +
      '  Call `tools/list` for the live catalogue with full input schemas — every tool\'s\n' +
      '  arguments are strictly validated and described.\n' +
      `- **Resources:** ${resources} read surfaces (campaign index, campaign summary, party,\n` +
      '  session recaps, session-zero charter, AI-authorized support preferences) exposed as\n' +
      '  MCP **resources** — call `resources/list` to discover concrete URIs.\n' +
      `- **Prompts:** ${prompts} authoring prompts (recap-writer, session-prep) — call\n` +
      '  `prompts/list` to discover them.',
  ],
]);

replace('website/docs/reference/roadmap.md', [
  [
    '- ✅ **Full MCP parity — 137 tools** covering campaign lifecycle',
    `- ✅ **Full MCP parity — ${tools} tools** covering campaign lifecycle`,
  ],
  [
    '- ✅ **MCP resources & prompts** — read surfaces are also exposed as MCP resources, plus prep/recap prompts, beyond the tool set',
    `- ✅ **MCP resources & prompts** — ${resources} read surfaces plus ${prompts} prep/recap prompts, beyond the ${tools}-tool set`,
  ],
  [
    '- ✅ **MCP resources & prompts** — read surfaces are exposed as MCP resources, with prep/recap prompts, beyond the tool set',
    `- ✅ **MCP resources & prompts** — ${resources} read surfaces plus ${prompts} prep/recap prompts, beyond the ${tools}-tool set`,
  ],
]);

replace('apps/web/src/i18n/locales/en/preferences.json', [
  [
    'Point Claude (or any MCP client) at this server to read and write your campaigns — 36+ tools covering quests, NPCs, characters, encounters, dice and more.',
    'Point Claude (or any MCP client) at this server to read and write your campaigns — {{toolCount}} tools covering quests, NPCs, characters, encounters, dice and more.',
  ],
]);

replace('apps/web/src/i18n/locales/ar/preferences.json', [
  [
    'Point Claude (or any MCP client) at this server to read and write your campaigns — 36+ tools covering quests, NPCs, characters, encounters, dice and more.',
    'Point Claude (or any MCP client) at this server to read and write your campaigns — {{toolCount}} tools covering quests, NPCs, characters, encounters, dice and more.',
  ],
]);

console.log(
  `generate-mcp-catalog-surfaces: ok — ${tools} tools, ${resources} resources, ${prompts} prompts`,
);
